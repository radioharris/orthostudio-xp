"""A start on a runway or a stand is built round where X-Plane places the aircraft, its threshold
or the stand in apt.dat, not round the airport's own point (LSGG, 2026-10-20)."""

from __future__ import annotations

import time
from pathlib import Path

from orthostudio.live.gate import start_position
from orthostudio.live.route import AirportIndex, airport_offsets, start_spot

APT = """I
1200 Generated by WorldEditor

1   1410 0 0 LSGG Geneva
1302 datum_lat 46.238333333
1302 datum_lon 6.109444444
100 54.86 2 0 0.00 1 3 0 04 46.2257938 6.0909393 329 20 3 3 0 3 22 46.2503975 6.1270615 0 20 3 4 1 2
102 H1 46.2400 6.1100 0.0 20 20 2 0 0 0.25 0
1300 46.245375 6.124862 135.7 tie_down jets 48A
1300 46.2440 6.1230 90.0 gate jets Gate  12
101 49 1 W1 46.2000 6.1500 W2 46.2100 6.1600

1   1616 0 0 LFLI Annemasse
1302 datum_lat 46.191
1302 datum_lon 6.268
100 30 1 0 0 0 0 0 12 46.19 6.25 0 0 0 0 0 0 30 46.192 6.28 0 0 0 0 0 0
99
"""


def write_apt(tmp_path: Path) -> Path:
    path = tmp_path / "apt.dat"
    path.write_text(APT)
    return path


def test_a_runway_s_threshold_and_a_stand(tmp_path: Path) -> None:
    apt = write_apt(tmp_path)
    at = airport_offsets(apt)["LSGG"]
    assert start_spot(apt, at, "04", None) == (46.2257938, 6.0909393)
    assert start_spot(apt, at, "4", None) == (46.2257938, 6.0909393)
    assert start_spot(apt, at, "22", None) == (46.2503975, 6.1270615)
    assert start_spot(apt, at, "H1", None) == (46.24, 6.11)
    assert start_spot(apt, at, "W2", None) == (46.21, 6.16)
    assert start_spot(apt, at, None, "48A") == (46.245375, 6.124862)
    assert start_spot(apt, at, None, "Gate 12") == (46.244, 6.123)
    assert start_spot(apt, at, "12", None) is None  # Annemasse's, not Geneva's
    assert start_spot(apt, at, None, None) is None


def test_a_saved_start_is_its_threshold_once_the_index_is_read(tmp_path: Path) -> None:
    index = AirportIndex(write_apt(tmp_path))
    deadline = time.time() + 10
    while index._offsets is None and time.time() < deadline:
        time.sleep(0.01)
    start = {"runway_start": {"airport_id": "lsgg", "runway": "04"}}
    assert start_position(start, index) == (46.2257938, 6.0909393, "LSGG runway 04")
    unknown = {"runway_start": {"airport_id": "LSGG", "runway": "99"}}
    assert start_position(unknown, index) == (46.238333333, 6.109444444, "LSGG runway 99")
