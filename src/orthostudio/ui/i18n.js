// ------------------------------------------------------------ paths, as the reader sees them

let userHome = "";

/** The home folder of whoever runs the engine (``/api/status`` ``user_home``). */
export function setUserHome(path) {
  userHome = typeof path === "string" ? path : "";
}

/** A path under the home folder written with "~". It is shorter to read, and it keeps the name of
 * whoever runs OrthoStudio XP out of the pictures people post with a report. What the engine is
 * asked to open or to save is always the path itself, never this. */
export function homely(path) {
  if (typeof path !== "string" || !userHome) return path;
  if (path === userHome) return "~";
  for (const sep of ["/", "\\"]) {
    if (path.startsWith(userHome + sep)) return `~${path.slice(userHome.length)}`;
  }
  return path;
}

function locale() {
  return current === "fr" ? "fr-FR" : "en-US";
}

export function fmtInt(n) {
  if (n == null || Number.isNaN(n)) return "—";
  return new Intl.NumberFormat(locale(), { maximumFractionDigits: 0 }).format(n);
}

export function fmtNum(n, digits = 1) {
  if (n == null || Number.isNaN(n)) return "—";
  return new Intl.NumberFormat(locale(), {
    minimumFractionDigits: 0,
    maximumFractionDigits: digits,
  }).format(n);
}

export function fmtMB(mb) {
  if (mb == null) return "—";
  if (mb >= 1000) return `${fmtNum(mb / 1000, 2)} ${current === "fr" ? "Go" : "GB"}`;
  return `${fmtNum(mb, mb < 10 ? 1 : 0)} ${current === "fr" ? "Mo" : "MB"}`;
}

export function fmtGB(gb) {
  if (gb == null) return "—";
  if (gb < 1) return fmtMB(gb * 1000);
  return `${fmtNum(gb, gb < 10 ? 2 : 1)} ${current === "fr" ? "Go" : "GB"}`;
}

export function fmtBytes(b) {
  if (b == null) return "—";
  return fmtGB(b / 1e9);
}

/** A small size in kilobytes (a tile tried: "23 ko"). */
export function fmtKB(b) {
  if (b == null) return "—";
  return `${fmtInt(Math.max(1, Math.round(b / 1000)))} ${current === "fr" ? "ko" : "KB"}`;
}

export function fmtMbps(mbps) {
  if (mbps == null || mbps <= 0) return t("app.not_measured");
  return `${fmtNum(mbps, 1)} ${current === "fr" ? "Mo/s" : "MB/s"}`;
}

/** Ground size of a pixel for the detail levels, rounded (the labels say "about"): 40 cm, 2 m, 27 m. */
export function fmtGround(m) {
  if (m == null || !Number.isFinite(m) || m <= 0) return "—";
  if (m >= 0.95) return `${fmtInt(Math.round(m))} m`;
  const cm = m * 100;
  const step = cm >= 50 ? 10 : 5;
  return `${fmtInt(Math.max(5, Math.round(cm / step) * step))} cm`;
}

/** 45 s · 1 min 40 s · 3 min · 2 h 05 min */
export function fmtDuration(seconds) {
  if (seconds == null || Number.isNaN(seconds) || seconds < 0) return "—";
  const s = Math.round(seconds);
  if (s < 60) return `${s} s`;
  const m = Math.floor(s / 60);
  const rs = s % 60;
  if (m < 60) return rs ? `${m} min ${String(rs).padStart(2, "0")} s` : `${m} min`;
  const h = Math.floor(m / 60);
  const rm = m % 60;
  return `${h} h ${String(rm).padStart(2, "0")} min`;
}

/** "1 min 40 – 3 min"; collapses to one value when the bounds are equal. */
export function fmtRange(low, high) {
  if (low == null && high == null) return "—";
  if (low == null || high == null || Math.round(low) === Math.round(high)) {
    return fmtDuration(low ?? high);
  }
  return `${fmtDuration(low)} – ${fmtDuration(high)}`;
}

export function fmtDate(ts) {
  if (!ts) return "";
  const d = typeof ts === "number" ? new Date(ts * 1000) : new Date(ts);
  if (Number.isNaN(d.getTime())) return String(ts);
  return new Intl.DateTimeFormat(locale(), { dateStyle: "short", timeStyle: "short" }).format(d);
}

/** The name of a relief source as a build records it (``COP30``, ``HRDEM``...), in the page's
 * language; a path is a file or a folder of the user's own. */
export function reliefName(source) {
  const code = String(source || "");
  if (/[\\/]/.test(code) && code !== "NED1/3") return t("relief.name.own");
  return tOpt(`relief.name.${code}`) || code;
}

