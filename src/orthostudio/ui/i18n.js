let current = "en";

// Only a choice made in the language switch is kept.
const LANGUAGE_KEY = "osxp.language";

/** English whatever the browser's language (the user's decision, map-zones.md 7.0.7), unless the
 * switch chose otherwise. */
export function detectLanguage() {
  try {
    const stored = localStorage.getItem(LANGUAGE_KEY);
    if (stored === "fr" || stored === "en") return stored;
  } catch (_e) {
    // storage may be unavailable; fall through
  }
  return "en";
}

export function setLanguage(lang, remember = false) {
  current = lang === "fr" ? "fr" : "en";
  if (remember) {
    try {
      localStorage.setItem(LANGUAGE_KEY, current);
    } catch (_e) {
      // ignore
    }
  }
  document.documentElement.lang = current;
}

export function language() {
  return current;
}

export function languages() {
  return Object.keys(STRINGS);
}

function interpolate(text, params) {
  if (!params) return text;
  return text.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m));
}

/** Translate a literal key; missing keys return the key itself (visible, so tests catch it). */
export function t(key, params) {
  const table = STRINGS[current] || STRINGS.en;
  const text = table[key] ?? STRINGS.en[key] ?? key;
  return interpolate(text, params);
}

/** Translate a dynamic key; returns null when it is not defined. */
export function tOpt(key, params) {
  const table = STRINGS[current] || STRINGS.en;
  const text = table[key] ?? STRINGS.en[key];
  return text == null ? null : interpolate(text, params);
}

/** [message, remedy] for an error code, or null when the page does not know it; ``context`` is
 * the error's (a path, the tiles named). */
export function codeText(code, context = null) {
  const table = CODES[current] || CODES.en;
  const entry = table[code] ?? CODES.en[code] ?? null;
  if (entry == null) return null;
  const ctx = context && typeof context === "object" ? context : {};
  const words = typeof entry === "function" ? entry(ctx) : entry;
  return words.map((text) => interpolate(text, ctx));
}

/** Apply data-i18n / -title / -placeholder / -aria-label attributes in a subtree. */
export function applyStatic(root) {
  for (const el of root.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll("[data-i18n-title]")) el.title = t(el.dataset.i18nTitle);
  for (const el of root.querySelectorAll("[data-i18n-placeholder]")) {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  }
  for (const el of root.querySelectorAll("[data-i18n-aria-label]")) {
    el.setAttribute("aria-label", t(el.dataset.i18nAriaLabel));
  }
}

